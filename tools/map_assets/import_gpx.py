"""Pack a local WGS84 GPX as a small, build-time offline route."""
import argparse
import math
from pathlib import Path
import xml.etree.ElementTree as ET

MAX_POINTS = 256
MAX_SEGMENTS = 16
METERS_PER_DEGREE = 111320.0


def read_segments(path):
    root = ET.parse(path).getroot()
    if root.tag.split("}")[-1] != "gpx":
        raise ValueError("expected a GPX file")
    segments = [s.findall("{*}trkpt") for s in root.findall(".//{*}trkseg")]
    segments += [s.findall("{*}rtept") for s in root.findall("{*}rte")]
    result = []
    for segment in segments:
        if not segment:
            continue
        points = [(float(p.attrib["lat"]), float(p.attrib["lon"])) for p in segment]
        if any(not (-85 <= lat <= 85 and -180 <= lon <= 180) for lat, lon in points):
            raise ValueError("out-of-range GPS point; local maps support |latitude| <= 85 degrees")
        if len(points) >= 2:
            result.append(points)
    if not result or len(result) > MAX_SEGMENTS:
        raise ValueError(f"expected one to {MAX_SEGMENTS} track segments/routes with at least two points")
    return result


def simplify(points, tolerance):
    keep = {0, len(points) - 1}
    todo = [(0, len(points) - 1)]
    while todo:
        start, end = todo.pop()
        x, y = points[start]
        dx = points[end][0] - x
        dy = points[end][1] - y
        span = dx * dx + dy * dy
        best, far = None, tolerance ** 2
        for i in range(start + 1, end):
            px, py = points[i][0] - x, points[i][1] - y
            t = max(0, min(1, (px * dx + py * dy) / span)) if span else 0
            error = (px - t * dx) ** 2 + (py - t * dy) ** 2
            if error > far:
                best, far = i, error
        if best is not None:
            keep.add(best)
            todo.extend(((start, best), (best, end)))
    return [points[i] for i in sorted(keep)]


def pack(segments, tolerance):
    coords = [p for segment in segments for p in segment]
    minlat, maxlat = min(p[0] for p in coords), max(p[0] for p in coords)
    minlon, maxlon = min(p[1] for p in coords), max(p[1] for p in coords)
    lat_e7 = round((minlat + maxlat) * 5e6)
    lon_e7 = round((minlon + maxlon) * 5e6)
    lon_scale = METERS_PER_DEGREE * math.cos(math.radians(lat_e7 / 1e7))
    if (maxlon - minlon > 180 or (maxlat - minlat) * METERS_PER_DEGREE > 100000
            or (maxlon - minlon) * lon_scale > 100000):
        raise ValueError("choose a local GPX region no wider than 100 km without an antimeridian crossing")
    local = [[(round((lon-lon_e7/1e7)*lon_scale), round((lat-lat_e7/1e7)*METERS_PER_DEGREE))
              for lat, lon in segment] for segment in segments]
    simplified = [simplify(seg, tolerance) for seg in local]
    if not any(len(set(seg)) > 1 for seg in simplified):
        raise ValueError("route has no distinct points at meter resolution")
    if sum(map(len, simplified)) > MAX_POINTS:
        raise ValueError(f"more than {MAX_POINTS} points after simplification; increase --tolerance-m")
    lines = ["/* Generated by import_gpx.py; WGS84 local route, units in meters. */",
             "#define MAP_GEOREF 1",
             f"#define MAP_ORIGIN_LAT_E7 ({lat_e7})",
             f"#define MAP_ORIGIN_LON_E7 ({lon_e7})",
             f"#define MAP_LON_M_PER_DEG ({lon_scale:.9f})"]
    names = []
    for i, seg in enumerate(simplified):
        name = "route" if i == 0 else f"route_{i}"
        names.append(name)
        lines.append(f"static const point_t {name}[] = {{")
        lines.extend(f"    {{{x}, {y}}}," for x, y in seg)
        lines.append("};")
    lines.append("static const path_t paths[] = {")
    lines.extend(f"    {{{name}, sizeof({name})/sizeof(*{name}), ROUTE}}," for name in names)
    lines.append("};")
    return "\n".join(lines) + "\n", sum(map(len, simplified))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("gpx", type=Path)
    ap.add_argument("--output", required=True, type=Path)
    ap.add_argument("--tolerance-m", type=float, default=3)
    args = ap.parse_args()
    if not math.isfinite(args.tolerance_m) or args.tolerance_m < 0:
        ap.error("--tolerance-m must be finite and non-negative")
    try:
        text, count = pack(read_segments(args.gpx), args.tolerance_m)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="ascii")
    except (OSError, ValueError, KeyError, ET.ParseError) as err:
        ap.error(str(err))
    print(f"Packed {count} GPX points into {args.output}")


if __name__ == "__main__":
    main()
